def test_case_run_uses_contract_build_catalog(tmp_path, net, monkeypatch):
    root = kit_case(tmp_path, with_api=False)
    seen = {}
    from builder import openapi_model

    def build_catalog(case, mock_url, rd, budget=None):
        seen["contract"] = [d["rel"] for d in case["contract_docs"]]
        seen["mock"], seen["budget"] = mock_url, budget
        out = pathlib.Path(rd) / "openapi.json"
        out.write_text(json.dumps(ingest.with_server(json.loads(API.read_text()), mock_url)))
        cat = openapi_model.load(str(out))
        cat["contract"] = {"source": "derived", "openapi_path": str(out)}
        return cat
    import builder
    fake = types.SimpleNamespace(build_catalog=build_catalog)
    monkeypatch.setitem(sys.modules, "builder.contract", fake)
    monkeypatch.setattr(builder, "contract", fake, raising=False)
    assert main(tmp_path, root, MOCK) == build.EXIT_OK
    assert "Servisler.pdf" in seen["contract"] and seen["mock"] == MOCK and seen["budget"] is not None
    r = recs(run_dir(tmp_path))
    assert [x for x in r if x["kind"] == "INPUT" and x.get("role") == "tool_api"][0]["source"] == "derived"

    def broken(case, mock_url, rd, budget=None):
        raise openapi_model.CatalogError("no identity operation")
    fake.build_catalog = broken
    assert main(tmp_path, root, MOCK) == build.EXIT_INPUT


