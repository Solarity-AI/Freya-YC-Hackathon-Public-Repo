def test_from_case_marks_roles_and_protects_customer_values(tmp_path):
    root = kit_case(tmp_path)
    (root / "Not Defteri.md").write_text("# Başlık\nboşluklu ad\n")
    b = segment.from_case(ingest.load_case(root, MOCK))
    rels = [d["rel"] for d in b["docs"]]
    assert rels[:2] == ["BRIEF.md", "README.md"] and "Servis Sozlesmesi.json" not in rels and "resim.png" not in rels
    roles = b["case"]["roles"]
    assert roles["Musteriler.xlsx"] == "test_customers" and roles["konusmalar/ornek1.md"] == "example_conversation"
    assert b["case"]["mock_url"] == MOCK
    num = b["numbered"]
    assert "(role: test_customers; TEST DATA" in num and "(role: example_conversation; EXAMPLE CONVERSATION" in num
    assert "=== DOCUMENT 1 of" in num and "Not_Defteri.md:2| boşluklu ad" in num
    assert "Ayşe" in b["examples"] and "1988-03-15" in b["examples"]
    assert "Is_Analizi.docx:3| 1. Önce doğum tarihi sorulur." in num
    assert segment.quote_in("Önce doğum tarihi sorulur.", segment.norm_quote_text(b["text"]))
    one = segment.from_case({"docs": [{"path": str(root / "BRIEF.md"), "rel": "BRIEF.md", "kind": "brief",
                                       "text": "tek\n"}]})
    assert one["numbered"] == "BRIEF.md:1| tek\n"


def test_segment_of_a_folder_reads_word_excel_and_skips_lock_files(tmp_path):
    d = tmp_path / "ham"
    d.mkdir()
    (d / "brief.md").write_text("ana metin")
    rich_docx(d / "kurallar.docx")
    make_xlsx(d / "tablo.xlsx", [("S", CUSTOMER_ROWS)])
    (d / "~$kurallar.docx").write_bytes(b"lock")
    got = [pathlib.Path(p).name for p in segment.expand_paths([str(d)])]
    assert got == ["brief.md", "kurallar.docx", "tablo.xlsx"]
    b = segment.segment([str(d)])
    assert "# Kimlik" in b["text"] and "## Sheet: S" in b["text"]
    b2 = segment.segment([str(d / "brief.md"), str(d / "kurallar.docx")])            # files: layers, docx read too
    assert "=== LAYER 2 of 2: kurallar.docx" in b2["numbered"] and "1. Önce doğum tarihi sorulur." in b2["text"]


