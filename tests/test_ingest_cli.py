def test_case_with_renamed_operations_binds_through_the_contract_stage(tmp_path, net):
    """A case-folder OpenAPI whose operations have other (Turkish) names: the strict loader alone refuses it, the
    case form binds it through builder.contract and points every tool at the mock."""
    from builder import contract, openapi_model
    assert hasattr(contract, "build_catalog")
    root = kit_case(tmp_path, with_api=False)
    api = json.loads(API.read_text())
    api["paths"] = {RENAMED.get(k, k): v for k, v in api["paths"].items()}
    for item in api["paths"].values():
        for op in item.values():
            if isinstance(op, dict):
                op.pop("operationId", None)
    (root / "servis_sozlesmesi.json").write_text(json.dumps(api, ensure_ascii=False))
    with pytest.raises(openapi_model.CatalogError):
        openapi_model.load(str(root / "servis_sozlesmesi.json"))
    assert build.parse_args([str(root), MOCK]).api.endswith("servis_sozlesmesi.json")
    assert main(tmp_path, root, MOCK) == build.EXIT_OK
    cat = json.loads((run_dir(tmp_path) / "catalog.json").read_text())
    assert cat["server"] == MOCK and not cat["contract"]["absent"]
    assert cat["contract"]["op_map"]["verify_identity"] == "POST /kimlik_dogrula"
    assert cat["contract"]["op_map"]["create_promise"] == "POST /odeme_sozu_kaydet"
    assert MOCK + "/openapi.json" not in net["seen"]                           # the folder's file won


