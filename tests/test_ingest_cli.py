def test_parse_zip_and_bad_inputs(tmp_path):
    root = kit_case(tmp_path)
    shutil.make_archive(str(tmp_path / "Teslim"), "zip", root.parent, root.name)
    ns = build.parse_args([str(tmp_path / "Teslim.zip"), MOCK])
    assert ns.case_name == "Teslim" and pathlib.Path(ns.case).name == "Vaka-Kart" and ns.zip_src.endswith(".zip")
