@pytest.mark.parametrize("with_contract", [False, True])
def test_case_run_traces_every_file_and_points_tools_at_the_mock(tmp_path, net, monkeypatch, with_contract):
    if not with_contract:
        _no_contract(monkeypatch)
    root = kit_case(tmp_path)
    assert main(tmp_path, root, MOCK) == build.EXIT_OK
    rd = run_dir(tmp_path)
    r = recs(rd)
    start = [x for x in r if x["kind"] == "START"][0]
    assert start["input_form"] == "case_folder" and start["mock_url"] == MOCK and start["case"] == str(root)
    inputs = {x["msg"]: x for x in r if x["kind"] == "INPUT"}
    assert inputs["Is_Analizi.docx"]["doc_kind"] == "analysis" and inputs["Is_Analizi.docx"]["bytes"] > 0
    assert inputs["resim.png"]["status"] == "skipped"
    assert any(x["kind"] == "WARN" and "resim.png" in x["msg"] for x in r)
    assert [x for x in r if x["kind"] == "INPUT" and x.get("role") == "mock"][0]["url"] == MOCK
    cat = [x for x in r if x["kind"] == "CATALOG" and x.get("server")][-1]
    assert cat["server"] == MOCK
    api_ev = [x for x in r if x["kind"] == "INPUT" and x.get("role") == "tool_api"][0]
    assert json.loads(pathlib.Path(api_ev["msg"]).read_text())["servers"] == [{"url": MOCK}]
    segs = [x for x in r if x["kind"] == "SEGMENT"]
    assert segs[0]["msg"] == "BRIEF.md" and segs[1]["msg"] == "README.md"
    assert "Servis Sozlesmesi.json" not in [x["msg"] for x in segs]             # the tool API is not a brief doc
    man = json.loads((rd / "case_manifest.json").read_text())
    assert man["mock_url"] == MOCK and any(f["rel"] == "Musteriler.xlsx" for f in man["files"])
    assert net["seen"] == [MOCK + "/health"]


