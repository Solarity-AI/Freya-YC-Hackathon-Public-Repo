def kit_case(tmp_path, with_api=True):
    root = make_case(tmp_path / "Vaka-Kart")
    (root / "api.json").unlink()
    if with_api:
        shutil.copy(API, root / "Servis Sozlesmesi.json")
    return root


def recs(rd):
    return [json.loads(x) for x in (rd / "trace.jsonl").read_text().splitlines() if x.strip()]


def run_dir(tmp_path):
    return sorted((tmp_path / "out").glob("*/r*"))[-1]


def main(tmp_path, *argv):
    return build.main([*map(str, argv), "--no-deploy", "--no-twin", "--spec-in", str(GOLDEN),
                       "--out-dir", str(tmp_path / "out")])


