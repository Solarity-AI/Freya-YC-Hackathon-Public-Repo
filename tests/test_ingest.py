def make_pdf(path, lines):
    """A minimal valid one-page PDF with Helvetica text lines (xref offsets computed)."""
    content = "BT /F1 12 Tf 72 720 Td " + " ".join("(%s) Tj 0 -16 Td" % ln.replace("(", "\\(").replace(")", "\\)")
                                                for ln in lines) + " ET"
    objs = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> "
            "/Contents 5 0 R >>", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
            "<< /Length %d >>\nstream\n%s\nendstream" % (len(content), content)]
    out = b"%PDF-1.4\n"
    offs = []
    for i, o in enumerate(objs, 1):
        offs.append(len(out))
        out += ("%d 0 obj\n%s\nendobj\n" % (i, o)).encode("latin-1")
    xref = len(out)
    out += ("xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)).encode()
    out += "".join("%010d 00000 n \n" % o for o in offs).encode()
    out += ("trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)).encode()
    pathlib.Path(path).write_bytes(out)


DRAWIO_MODEL = ('<mxGraphModel><root><mxCell id="0"/><mxCell id="1" parent="0"/>'
                '<mxCell id="a" value="Kimlik &lt;b&gt;doğrula&lt;/b&gt;" vertex="1" parent="1"/>'
                '<mxCell id="b" value="Borcu söyle" vertex="1" parent="1"/>'
                '<object id="c" label="Kapat"><mxCell vertex="1" parent="1"/></object>'
                '<mxCell id="e1" value="evet" edge="1" source="a" target="b" parent="1"/>'
                '<mxCell id="e2" edge="1" source="b" target="c" parent="1"/>'
                '<mxCell id="l2" value="söz alındı" vertex="1" connectable="0" parent="e2"/>'
                '<mxCell id="e3" edge="1" source="a" parent="1"/>'
                "</root></mxGraphModel>")


def compressed_drawio(path):
    raw = urllib.parse.quote(DRAWIO_MODEL)
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = base64.b64encode(c.compress(raw.encode()) + c.flush()).decode()
    pathlib.Path(path).write_text('<mxfile><diagram name="Akış">%s</diagram></mxfile>' % data)


