# ------------------------------------------------------------------------------------------- file factories

def _p(text, style=None, num=None, ilvl=0):
    ppr = ""
    if style or num:
        ppr = "<w:pPr>%s%s</w:pPr>" % ('<w:pStyle w:val="%s"/>' % style if style else "",
                                       '<w:numPr><w:ilvl w:val="%d"/><w:numId w:val="%s"/></w:numPr>' % (ilvl, num)
                                       if num else "")
    return "<w:p>%s<w:r><w:t xml:space=\"preserve\">%s</w:t></w:r></w:p>" % (ppr, text)


def _tc(inner, span=None, vmerge=None):
    pr = ""
    if span or vmerge:
        pr = "<w:tcPr>%s%s</w:tcPr>" % ('<w:gridSpan w:val="%d"/>' % span if span else "",
                                        ('<w:vMerge w:val="%s"/>' % vmerge) if vmerge == "restart"
                                        else ("<w:vMerge/>" if vmerge else ""))
    return "<w:tc>%s%s</w:tc>" % (pr, inner)


def make_docx(path, body, styles=True, numbering=True, extra=None):
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("[Content_Types].xml", "<Types/>")
        z.writestr("word/document.xml", "<w:document %s><w:body>%s<w:sectPr/></w:body></w:document>" % (W_NS, body))
        if styles:
            z.writestr("word/styles.xml", "<w:styles %s>"
                       '<w:style w:styleId="Balk1"><w:name w:val="heading 1"/></w:style>'
                       '<w:style w:styleId="Balk2"><w:name w:val="heading 2"/></w:style>'
                       '<w:style w:styleId="KonuBal"><w:name w:val="Title"/></w:style>'
                       '<w:style w:styleId="Ozel"><w:name w:val="Ozel"/><w:pPr><w:outlineLvl w:val="2"/></w:pPr>'
                       "</w:style></w:styles>" % W_NS)
        if numbering:
            z.writestr("word/numbering.xml", "<w:numbering %s>"
                       '<w:abstractNum w:abstractNumId="0">'
                       '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="decimal"/><w:lvlText w:val="%%1."/></w:lvl>'
                       '<w:lvl w:ilvl="1"><w:start w:val="1"/><w:numFmt w:val="lowerLetter"/>'
                       '<w:lvlText w:val="%%2)"/></w:lvl></w:abstractNum>'
                       '<w:abstractNum w:abstractNumId="1"><w:lvl w:ilvl="0"><w:numFmt w:val="bullet"/>'
                       '<w:lvlText w:val="*"/></w:lvl></w:abstractNum>'
                       '<w:abstractNum w:abstractNumId="2"><w:lvl w:ilvl="0"><w:start w:val="4"/>'
                       '<w:numFmt w:val="upperRoman"/><w:lvlText w:val="%%1."/></w:lvl></w:abstractNum>'
                       '<w:num w:numId="1"><w:abstractNumId w:val="0"/></w:num>'
                       '<w:num w:numId="2"><w:abstractNumId w:val="1"/></w:num>'
                       '<w:num w:numId="3"><w:abstractNumId w:val="2"/></w:num>'
                       "</w:numbering>" % W_NS)
        for name, xml in (extra or {}).items():
            z.writestr(name, xml)


def rich_docx(path):
    textbox = ('<w:p><w:r><mc:AlternateContent><mc:Choice Requires="wps"><w:drawing><wps:txbx><w:txbxContent>'
               + _p("Kutudaki not: hafta sonu arama yok") + "</w:txbxContent></wps:txbx></w:drawing></mc:Choice>"
               "<mc:Fallback><w:pict><w:txbxContent>" + _p("Kutudaki not: hafta sonu arama yok")
               + "</w:txbxContent></w:pict></mc:Fallback></mc:AlternateContent></w:r>"
               "<w:r><w:t>Gövde metni</w:t></w:r></w:p>")
    nested = "<w:tbl><w:tr>%s%s</w:tr><w:tr>%s%s</w:tr></w:tbl>" % (
        _tc(_p("iç1")), _tc(_p("iç2")), _tc(_p("iç3")), _tc(_p("iç4")))
    table = ("<w:tbl><w:tblPr/><w:tblGrid/>"
             "<w:tr>%s%s%s</w:tr>" % (_tc(_p("Kod")), _tc(_p("Anlam")), _tc(_p("Not")))
             + "<w:tr>%s%s%s</w:tr>" % (_tc(_p("X1"), vmerge="restart"), _tc(_p("birinci | pipe")), _tc(nested))
             + "<w:tr>%s%s</w:tr>" % (_tc(_p(""), vmerge="continue"), _tc(_p("geniş hücre"), span=2))
             + "<w:sdt><w:sdtContent><w:tr>%s%s%s</w:tr></w:sdtContent></w:sdt>" % (
                 _tc(_p("Y2")), _tc(_p("satır") + _p("iki paragraf")), _tc(_p("-")))
             + "</w:tbl>")
    body = (_p("Kurallar Belgesi", "KonuBal") + _p("Kimlik", "Balk1") + _p("Önce doğum tarihi sorulur.", num="1")
            + _p("Sonra telefon.", num="1") + _p("alt madde", num="1", ilvl=1) + _p("Üçüncü kural.", num="1")
            + _p("madde işareti", num="2") + _p("Roma", num="3") + _p("Bölüm", "Balk2") + _p("Özel başlık", "Ozel")
            + textbox + "<w:sdt><w:sdtContent>" + _p("İçerik denetimi içindeki metin") + "</w:sdtContent></w:sdt>"
            + '<w:p><w:r><w:t>silinmeyen</w:t></w:r><w:del><w:r><w:delText>SİLİNDİ</w:delText></w:r></w:del>'
            '<w:r><w:tab/><w:t>sekme</w:t><w:br/><w:t>satır sonu</w:t></w:r></w:p>' + table)
    make_docx(path, body, extra={
        "word/header1.xml": "<w:hdr %s>%s</w:hdr>" % (W_NS, _p("Gizli - iç kullanım")),
        "word/footer1.xml": "<w:ftr %s>%s</w:ftr>" % (W_NS, _p("Gizli - iç kullanım")),
        "word/footnotes.xml": "<w:footnotes %s><w:footnote>%s</w:footnote></w:footnotes>" % (
            W_NS, _p("Dipnot: tutarlar TL")),
    })


def make_xlsx(path, sheets, date1904=False, shared=("ad", "doğum tarihi", "Ayşe"), rels=True):
    """sheets: [(name, sheet_xml_rows)]; style 1 = a date format (builtin 14), style 2 = custom 'dd.mm.yyyy'."""
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("[Content_Types].xml", "<Types/>")
        sh = "".join('<sheet name="%s" sheetId="%d" r:id="rId%d"/>' % (n, i + 1, i + 1) for i, (n, _) in
                     enumerate(sheets))
        z.writestr("xl/workbook.xml", '<workbook %s>%s<sheets>%s</sheets></workbook>' % (
            S_NS, '<workbookPr date1904="1"/>' if date1904 else "", sh))
        if rels:
            # targets deliberately in reverse file order: the reader must follow the rels, not the file names
            rel = "".join('<Relationship Id="rId%d" Target="worksheets/sheet%d.xml"/>' % (i + 1, len(sheets) - i)
                          for i in range(len(sheets)))
            z.writestr("xl/_rels/workbook.xml.rels",
                       '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">%s'
                       "</Relationships>" % rel)
        z.writestr("xl/sharedStrings.xml", '<sst %s>%s<si><r><t>zen</t></r><r><t>gin</t></r>'
                   '<rPh><t>FURIGANA</t></rPh></si></sst>' % (S_NS, "".join("<si><t>%s</t></si>" % s for s in shared)))
        z.writestr("xl/styles.xml", '<styleSheet %s><numFmts><numFmt numFmtId="164" formatCode="dd\\.mm\\.yyyy"/>'
                   '<numFmt numFmtId="165" formatCode="#,##0.00 &quot;TL&quot;"/></numFmts>'
                   '<cellXfs><xf numFmtId="0"/><xf numFmtId="14"/><xf numFmtId="164"/><xf numFmtId="165"/>'
                   "</cellXfs></styleSheet>" % S_NS)
        for i, (_, rows) in enumerate(sheets):
            target = len(sheets) - i if rels else i + 1
            z.writestr("xl/worksheets/sheet%d.xml" % target,
                       "<worksheet %s><sheetData>%s</sheetData></worksheet>" % (S_NS, rows))


