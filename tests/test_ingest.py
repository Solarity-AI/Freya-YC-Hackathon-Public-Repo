def test_docx_reader_keeps_structure(tmp_path):
    rich_docx(tmp_path / "a.docx")
    text, tables = ingest.docx_read(tmp_path / "a.docx")
    lines = text.split("\n")
    assert "# Kurallar Belgesi" in lines and "# Kimlik" in lines and "## Bölüm" in lines and "### Özel başlık" in lines
    assert "1. Önce doğum tarihi sorulur." in lines and "2. Sonra telefon." in lines
    assert "  a) alt madde" in lines and "3. Üçüncü kural." in lines            # deeper level, then back up
    assert "- madde işareti" in lines and "IV. Roma" in lines
    assert text.count("Kutudaki not: hafta sonu arama yok") == 1                 # text box once (Fallback skipped)
    assert "Gövde metni" in text and "İçerik denetimi içindeki metin" in text
    assert "SİLİNDİ" not in text and "silinmeyen sekme" in text and "satır sonu" in text
    assert "| Kod | Anlam | Not |" in lines and "|---|---|---|" in lines
    assert "| X1 | birinci \\| pipe | iç1 / iç2; iç3 / iç4 |" in lines             # escaped pipe, nested table
    assert "| X1 | geniş hücre |  |" in lines                                    # vMerge copies, gridSpan pads
    assert "| Y2 | satır <br> iki paragraf | - |" in lines                         # rows inside a content control
    assert tables[0]["header"] == ["Kod", "Anlam", "Not"] and len(tables[0]["rows"]) == 3
    assert text.count("[header] Gizli - iç kullanım") == 1 and "[footer]" not in text   # duplicates dropped
    assert "[footnote] Dipnot: tutarlar TL" in text


