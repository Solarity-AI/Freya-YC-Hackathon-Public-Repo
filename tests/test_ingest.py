def test_pdf_reader_fallbacks(tmp_path, monkeypatch):
    make_pdf(tmp_path / "s.pdf", ["x"])

    class R:
        returncode, stdout = 0, b"   "
    text, _, warns = ingest.pdf_read(tmp_path / "s.pdf", run=lambda *a, **k: R(), which=lambda n: "/bin/x")
    assert text == "" and any("no extractable text" in w for w in warns)

    class Bad:
        returncode, stdout = 3, b""
    _, _, warns = ingest.pdf_read(tmp_path / "s.pdf", run=lambda *a, **k: Bad(), which=lambda n: "/bin/x")
    assert "pdftotext failed (exit 3)" in warns

    def boom(*a, **k):
        raise subprocess.TimeoutExpired("pdftotext", 1)
    _, _, warns = ingest.pdf_read(tmp_path / "s.pdf", run=boom, which=lambda n: None if n else None)
    assert any("no PDF reader" in w or "pypdf" in w or "no extractable" in w for w in warns)
    _, _, warns = ingest.pdf_read(tmp_path / "s.pdf", run=boom, which=lambda n: "/bin/x")
    assert "pdftotext failed: TimeoutExpired" in warns

    class Pages:
        returncode, stdout = 0, "sayfa bir\fsayfa iki\f".encode()
    text, _, _ = ingest.pdf_read(tmp_path / "s.pdf", run=lambda *a, **k: Pages(), which=lambda n: "/bin/x")
    assert text.split("\n")[:4] == ["[page 1]", "sayfa bir", "[page 2]", "sayfa iki"]


